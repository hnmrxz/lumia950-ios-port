#!/usr/bin/env python3
r"""Stage a kernel beside the UniXNU menu, for the chainload route.

    python3 scripts/stage-kernel.py --kernel build/kernel/kernel.macho --unique-chip-id HEX \
        [--trustcache FILE] [--data FILE] [--ntfs-driver FILE] \
        [--out build/boot] [--payload-out build/mainos]

Two placements are staged. Without --payload-out the whole tree goes on EFIESP, which only
works while the kernel and its sidecars fit in the partition. With --payload-out the menu,
its configuration and the drivers stay in --out for EFIESP, and Payloads/ (the kernel and
its sidecars) is written to --payload-out for MainOS: the prelinked image is 56 MB and
EFIESP is 32 MB, so that is where the kernel has to live. DarwinBoot is what makes the
split work — it reads the kernel from whichever volume holds it — and it only reaches
MainOS at all because --ntfs-driver stages a driver for that NTFS volume, which the
Lumia's own firmware image does not have (scripts/get-ntfs-driver.py fetches it).

The menu stage is what the phone has run: UniXNU finds its configuration on EFIESP, draws on
the panel and takes the volume keys (scripts/build-payload.sh). This adds the second stage to
the same tree: DarwinBoot as a driver, an `xnu` entry that hands it the kernel and the ADT
sidecar, and the files the loader reads beside the kernel (`<kernel>.adt`, `<kernel>.trustcache`).

The target is a build product: this script deletes it and recreates it, it does not merge into
it. So the stage refuses the repository root, a drive or volume root, a mount point, and any
non-empty directory outside `build/` and `out/` unless `--force` says otherwise — a `--out .`
or a `--out` naming a mounted EFIESP would otherwise take the checkout or the phone's boot
partition with it.

Nothing here reaches the phone unchecked. The kernel must be a 64-bit ARM Mach-O executable
(DarwinBoot parses it as one and refuses anything else), the ADT is generated by the board's
own tool and accepted by its checker, and scripts/check-payload.py re-reads the staged
configuration and requires every file it names to be in the tree. The result is a plain FAT
directory, so nothing is flashed: it is copied over \EFI on EFIESP or onto the microSD card.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

try:
    import tomllib
except ModuleNotFoundError:  # pragma: no cover - the CI runner has 3.11
    sys.exit("python3.11 or newer is required (tomllib)")

ROOT = Path(__file__).resolve().parents[1]
# scripts/ is not a package; the shared ADT profile resolver is one file beside this one.
sys.path.insert(0, str(Path(__file__).resolve().parent))
from board_profile import resolve_profile  # noqa: E402  (import after the path is set)
import menu_render  # noqa: E402

BASE_TREE = ROOT / "payload"
# The two directories that hold build products. A staged tree is deleted and recreated on every
# run, so replacing an existing directory on purpose may only reach into these.
PRODUCT_ROOTS = (ROOT / "build", ROOT / "out")
CONFIG_REL = "EFI/UniXNU/unixnu.toml"
PAYLOADS_REL = "EFI/UniXNU/Payloads"
KERNEL_NAME = "kernel.macho"

# The line in payload/EFI/UniXNU/unixnu.toml that the kernel entry replaces. scripts/menu_render.py
# owns it now, because stage-native-bringup.py renders the same file through the same marker.
MARKER = menu_render.MARKER

# DarwinBoot's own limits: it copies the command line into a 1024-byte buffer, and the ADT
# tool and payload step already refuse anything longer than 1000 bytes.
ARGUMENT = re.compile(r"[A-Za-z0-9_.\-]+(=[A-Za-z0-9_.,\-]+)?")

MH_MAGIC_64 = 0xFEEDFACF
MH_EXECUTE = 0x2
CPU_TYPE_ARM64 = 0x0100000C


def fail(message: str):
    print(f"error: {message}", file=sys.stderr)
    raise SystemExit(1)


def check_output_target(path: Path, flag: str, force: bool) -> None:
    """Refuse a staging directory whose removal would destroy something that is not a build.

    The stage deletes its target before copying the menu tree over it. That is fine for a
    previous build and catastrophic for the checkout, a drive root, a mounted EFIESP volume, or
    any other directory that holds work. scripts/stage-native-bringup.py made the same call the
    other way round (it refuses any existing directory); this script keeps the re-run workflow
    of the build tree, so an existing directory is accepted only inside build/ or out/, and only
    with --force.
    """
    resolved = path.resolve()
    root = ROOT.resolve()
    if resolved == root or resolved in root.parents:
        fail(f"{flag} {path} is the repository root or one of its parents (a drive root, or /); "
             "the stage deletes its target first, so that would replace the checkout or an "
             "entire volume")
    if os.path.ismount(resolved):
        fail(f"{flag} {path} is a mount point; the stage deletes its target first, and on a "
             "phone that path is the EFIESP volume the firmware boots from")
    if not resolved.exists():
        return
    if not resolved.is_dir():
        fail(f"{flag} {path} exists and is not a directory")
    if not any(resolved.iterdir()):
        return
    # resolve() each root: on Windows a temp path can come back in its 8.3 form and then never
    # match the long form a caller's path resolves to.
    products = tuple(candidate.resolve() for candidate in PRODUCT_ROOTS)
    if not any(resolved == product or product in resolved.parents for product in products):
        fail(f"{flag} {path} holds files and is not under build/ or out/; the stage deletes its "
             "target first, so stage into a new directory instead")
    if not force:
        fail(f"{flag} {path} already holds files; the stage replaces the whole tree, so pass "
             "--force to replace it, or stage into a new directory")


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def board_section() -> dict:
    board_path = ROOT / "board.toml"
    if not board_path.is_file():
        fail(f"{board_path} is missing; run this from the device repository")
    board = tomllib.loads(board_path.read_text())
    spec = board.get("payload")
    if not spec:
        fail("board.toml has no [payload]; it names the kernel arguments, the DRAM size and "
             "the ADT generator this stage runs (see the section's comment in board.toml)")
    if not (spec.get("adt") or {}).get("tool"):
        fail("board.toml [payload.adt] has no tool; it is the ADT generator for this SoC")
    return spec


def board_profile() -> dict:
    """The ADT profile both stagers share: one answer for CPU count, PSCI and DRAM.

    scripts/board_profile.py holds the rules. Reading the profile here instead of assembling the
    generator flags locally is what keeps this stage and stage-native-bringup.py from staging two
    different trees for the same phone.
    """
    return resolve_profile(ROOT / "board.toml")


def check_kernel(path: Path) -> dict:
    """The header DarwinBoot parses. Refusing here is cheaper than an EFI_LOAD_ERROR on a panel."""
    size = path.stat().st_size
    if size < 32:
        fail(f"{path} is {size} bytes; that is not a Mach-O")
    head = path.read_bytes()[:32]
    magic, cputype, cpusubtype, filetype, ncmds, sizeofcmds = (
        int.from_bytes(head[0:4], "little"), int.from_bytes(head[4:8], "little"),
        int.from_bytes(head[8:12], "little"), int.from_bytes(head[12:16], "little"),
        int.from_bytes(head[16:20], "little"), int.from_bytes(head[20:24], "little"))
    if magic != MH_MAGIC_64:
        fail(f"{path} does not start with MH_MAGIC_64 (0x{magic:08x}); DarwinBoot parses a "
             "64-bit Mach-O and this is not one")
    if cputype != CPU_TYPE_ARM64:
        fail(f"{path} is cputype 0x{cputype:08x}; this kernel has to be CPU_TYPE_ARM64")
    if filetype != MH_EXECUTE:
        fail(f"{path} is filetype 0x{filetype:08x}; DarwinBoot requires MH_EXECUTE (0x2)")
    if ncmds == 0 or sizeofcmds == 0 or 32 + sizeofcmds > size:
        fail(f"{path} has {ncmds} load commands taking {sizeofcmds} bytes in a {size}-byte "
             "file; the header does not describe its own contents")
    return {"size": size, "ncmds": ncmds}


def kernel_arguments(spec: dict, override: str | None) -> str:
    arguments = spec.get("kernel_args", [])
    if not isinstance(arguments, list) or not all(isinstance(item, str) for item in arguments):
        fail("board.toml [payload] kernel_args is not an array of strings")
    if override is not None:
        arguments = override.split()
    for argument in arguments:
        if not ARGUMENT.fullmatch(argument):
            fail(f"unsupported kernel argument: {argument!r}")
    line = " ".join(arguments)
    if len(line) > 1000:
        fail(f"the kernel command line is {len(line)} bytes; DarwinBoot's buffer is 1024")
    return line


def adt_command(profile: dict, spec: dict, adt: Path, args: argparse.Namespace) -> list[str]:
    values = spec.get("adt") or {}
    command = [sys.executable, str(ROOT / profile["tool"]), "--output", str(adt),
               "--dram-size", hex(profile["dram_size"])]
    if profile.get("owned_memory_size") is not None:
        command += ["--owned-memory-size", hex(profile["owned_memory_size"])]
    if profile.get("cpu_regs"):
        command += ["--cpu-regs", str(profile["cpu_regs"])]
    if profile.get("psci_method"):
        command += ["--psci-method", str(profile["psci_method"])]
    chip_id = args.chip_id if args.chip_id is not None else profile.get("chip_id")
    if chip_id is not None:
        command += ["--chip-id", hex(chip_id) if isinstance(chip_id, int) else str(chip_id)]
    for key, flag in (("root_match_volume_uuid", "--root-match-volume-uuid"),):
        if values.get(key) is not None:
            command += [flag, str(values[key])]
    dram_base = args.dram_base if args.dram_base is not None else profile.get("dram_base")
    if dram_base is not None:
        command += ["--dram-base", hex(dram_base)]
    # Only an emulated profile carries these; on the phone the generator's defaults are the SoC's.
    if profile.get("gic_distributor"):
        command += ["--gic-distributor", str(profile["gic_distributor"])]
    if profile.get("gic_cpu_interface"):
        command += ["--gic-cpu-interface", str(profile["gic_cpu_interface"])]
    if profile.get("soc_base"):
        command += ["--soc-base", hex(profile["soc_base"])]
    command += ["--unique-chip-id", args.unique_chip_id]
    if args.trustcache:
        command.append("--trust-cache")
    if args.data:
        command.append("--packed-data-ramdisk" if values.get("packed_data_ramdisk")
                       else "--data-ramdisk")
        if values.get("persistent_data"):
            command.append("--persistent-data")
    for fixup in spec.get("text_fixups", []):
        command += ["--text-fixup", fixup]
    return command


def render_config(spec: dict, menu_tree: Path, initrd: bool, arguments: str,
                  ntfs: bool) -> str:
    source = (menu_tree / CONFIG_REL).read_text()
    title = spec.get("title", "UniXNU")
    if '"' in title or "\\" in title:
        fail(f'board.toml [payload] title {title!r} cannot go in a TOML string unchanged')
    # The NTFS driver comes first: it has to be started and connected before the kernel on
    # MainOS is a file at all, and drivers are started in the order they appear here.
    entry = ''
    if ntfs:
        entry += '[[driver]]\npath = "Drivers/ntfs.efi"\nconnect = true\n\n'
    entry += (f'[[driver]]\npath = "Drivers/DarwinBoot.efi"\nconnect = true\n\n'
              f'[[entry]]\nid = "xnu"\ntitle = "{title}"\ntype = "xnu"\n'
              f'path = "Payloads/{KERNEL_NAME}"\n')
    if initrd:
        entry += 'initrd = "Payloads/scratch-data.img"\n'
    entry += f'args = "{arguments}"\n'
    # The kernel is the entry this stage exists for, so it becomes the countdown default. The
    # menu-only config keeps "exit" because none of its entries can boot a kernel. The marker,
    # the replacement and the single-match rules are shared with stage-native-bringup.py.
    return menu_render.render(source, insert=entry, default="xnu")


def report_tree(label: str, tree: Path, where: str) -> None:
    staged = sorted(path for path in tree.rglob("*") if path.is_file())
    total = sum(path.stat().st_size for path in staged)
    print(f"== {label}: {tree}")
    for path in staged:
        print(f"  {path.relative_to(tree).as_posix():<44} {path.stat().st_size:>10} B  "
              f"{sha256(path)[:16]}")
    print(f"  {'total':<44} {total:>10} B")
    print(f"  {where}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--kernel", type=Path, required=True,
                        help="the kernel Mach-O, e.g. the kernel job's prelinked image")
    parser.add_argument("--trustcache", type=Path,
                        help="the trust cache bundle DarwinBoot validates, if the image needs one")
    parser.add_argument("--data", type=Path,
                        help="the Data ramdisk seed; it becomes Payloads/scratch-data.img")
    parser.add_argument("--menu-tree", type=Path,
                        help="the menu stage to add to: out/payload from build-payload.sh "
                             "(default: out/payload if it exists, else payload/)")
    parser.add_argument("--out", type=Path, default=ROOT / "build/boot",
                        help="the staged EFIESP tree (default: build/boot)")
    parser.add_argument("--payload-out", type=Path,
                        help="stage Payloads/ into this second tree, for MainOS, when the kernel "
                             "does not fit EFIESP; copy its EFI/UniXNU/Payloads to \\EFI\\UniXNU "
                             "on MainOS")
    parser.add_argument("--ntfs-driver", type=Path,
                        help="the NTFS driver from scripts/get-ntfs-driver.py, staged as "
                             "Drivers/ntfs.efi; without it nothing can read MainOS, and the "
                             "kernel has to stay in --out")
    parser.add_argument("--force", action="store_true",
                        help="replace an existing non-empty staging directory (only inside "
                             "build/ or out/; the repository root, a drive root and a mount "
                             "point are refused regardless)")
    parser.add_argument("--report", type=Path,
                        help="the prelink report beside the kernel image; when it says the "
                             "candidate is unqualified the stage refuses")
    parser.add_argument("--allow-unqualified", action="store_true",
                        help="stage a kernel the prelink report marks loadable = false (a "
                             "deliberate experiment; docs/native-bringup.md does not stage it)")
    parser.add_argument("--unique-chip-id", required=True,
                        help="64-bit platform seed in hex; it is not stored in this repository")
    parser.add_argument("--dram-size", type=lambda value: int(value, 0),
                        help="override board.toml [payload] dram_size")
    parser.add_argument("--dram-base", type=lambda value: int(value, 0),
                        help="override the ADT DRAM base (default: board.toml, or the SoC's zero base)")
    parser.add_argument("--chip-id", type=lambda value: int(value, 0),
                        help="override board.toml [payload.adt] chip_id")
    parser.add_argument("--args", help="override board.toml [payload] kernel_args")
    args = parser.parse_args()

    if not re.fullmatch(r"[0-9a-fA-F]{1,16}", args.unique_chip_id):
        fail(f"--unique-chip-id {args.unique_chip_id!r} is not 1-16 hex digits")
    spec = board_section()
    profile = board_profile()
    if args.dram_size is not None:
        profile = dict(profile, dram_size=args.dram_size)
    if not args.kernel.is_file():
        fail(f"kernel not found: {args.kernel}; pass the kernel job's artifact")
    header = check_kernel(args.kernel)
    # The CI artifact is a merged candidate: a source kernel with kernel extensions copied out of
    # an Apple kernelcache. Its own report says whether anything established that it loads, and
    # docs/native-bringup.md does not put it on a phone. This makes that sentence mechanical.
    if args.report is not None:
        if not args.report.is_file():
            fail(f"report not found: {args.report}")
        report = json.loads(args.report.read_text())
        if report.get("loadable") is False and not args.allow_unqualified:
            fail(f"{args.report} marks this candidate unqualified (loadable = false): the merge "
                 "copied Apple kernel extensions into a source kernel and nothing has shown the "
                 "result loads, relocates or runs. Stage it only as a deliberate experiment, "
                 "with --allow-unqualified")
    arguments = kernel_arguments(spec, args.args)
    for name, path in (("trust cache", args.trustcache), ("Data seed", args.data),
                       ("NTFS driver", args.ntfs_driver)):
        if path is not None and not path.is_file():
            fail(f"{name} not found: {path}")
    if args.ntfs_driver is not None and args.ntfs_driver.read_bytes()[:2] != b"MZ":
        fail(f"{args.ntfs_driver} is not a PE image; UniXNU would fail to start it and MainOS "
             "would stay unreadable")

    # The menu stage carries the two EFI binaries; the repository's payload/ directory only
    # carries the configuration, so adding a kernel to it directly would stage a tree the
    # firmware cannot start. Refusing here says which command produces the missing half.
    menu_tree = args.menu_tree or (ROOT / "out/payload" if (ROOT / "out/payload").is_dir()
                                   else BASE_TREE)
    if not menu_tree.is_absolute():
        menu_tree = ROOT / menu_tree
    if not (menu_tree / CONFIG_REL).is_file():
        fail(f"{menu_tree} has no {CONFIG_REL}; run scripts/build-payload.sh first")
    if not (menu_tree / "EFI/UniXNU/Drivers/DarwinBoot.efi").is_file():
        fail(f"{menu_tree} has no EFI/UniXNU/Drivers/DarwinBoot.efi; the menu stage is built "
             "by scripts/build-payload.sh, which puts the loader beside the menu")

    out = args.out if args.out.is_absolute() else ROOT / args.out
    if out.resolve() == menu_tree.resolve():
        fail("--out is the menu tree; stage into a new directory so the menu build stays intact")
    payload_root = out if args.payload_out is None else args.payload_out
    if not payload_root.is_absolute():
        payload_root = ROOT / payload_root
    if payload_root.resolve() == menu_tree.resolve():
        fail("--payload-out is the menu tree; stage into a new directory")
    split = payload_root.resolve() != out.resolve()
    if split and out.resolve() in payload_root.resolve().parents:
        fail(f"--payload-out {payload_root} is inside --out {out}; the EFIESP tree is what the "
             "firmware reads, so the payloads belong beside it, not under it")
    check_output_target(out, "--out", args.force)
    if split:
        check_output_target(payload_root, "--payload-out", args.force)
    # The stage replaces its targets before it copies anything into them, so an input that lives
    # inside one of them would be deleted before it was read. --kernel inside --out is the easy
    # one to hit: that is where the previous stage left the image.
    for label, source in (("--menu-tree", menu_tree), ("--kernel", args.kernel),
                          ("--trustcache", args.trustcache), ("--data", args.data),
                          ("--ntfs-driver", args.ntfs_driver)):
        if source is None:
            continue
        source = source.resolve()
        for flag, target in (("--out", out), ("--payload-out", payload_root)):
            target = target.resolve()
            if source == target or target in source.parents:
                fail(f"{label} {source} is inside {flag} {target}; the stage replaces that "
                     "directory before it reads its inputs, so the input would be gone")
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(menu_tree, out)
    if split and payload_root.exists():
        shutil.rmtree(payload_root)
    payloads = payload_root / PAYLOADS_REL
    payloads.mkdir(parents=True, exist_ok=True)

    shutil.copyfile(args.kernel, payloads / KERNEL_NAME)
    adt = payloads / f"{KERNEL_NAME}.adt"
    command = adt_command(profile, spec, adt, args)
    print("== adt: " + " ".join(command[1:]))
    result = subprocess.run(command, cwd=ROOT)
    if result.returncode != 0:
        fail("the ADT generator refused its arguments")
    checked = subprocess.run([sys.executable, str(ROOT / "scripts/check-adt.py"), str(adt),
                              "--profile", profile["profile"]],
                             cwd=ROOT)
    if checked.returncode != 0:
        fail("scripts/check-adt.py rejected the generated ADT")
    if args.trustcache:
        shutil.copyfile(args.trustcache, payloads / f"{KERNEL_NAME}.trustcache")
    if args.data:
        shutil.copyfile(args.data, payloads / "scratch-data.img")
    if args.ntfs_driver:
        drivers = out / "EFI/UniXNU/Drivers"
        drivers.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(args.ntfs_driver, drivers / "ntfs.efi")
    (out / CONFIG_REL).write_text(render_config(spec, menu_tree, bool(args.data), arguments,
                                               bool(args.ntfs_driver)))

    print("== check")
    command = [sys.executable, str(ROOT / "scripts/check-payload.py"),
               "--config", str(out / CONFIG_REL), "--payload-dir", str(out)]
    if split:
        # Every name in the configuration still has to exist somewhere; with a split tree the
        # kernel and its sidecars are in the second one.
        command += ["--payload-files", str(payload_root)]
    checked = subprocess.run(command, cwd=ROOT)
    if checked.returncode != 0:
        fail("the staged tree does not pass scripts/check-payload.py")

    report_tree("EFIESP tree", out,
                "copy EFI over \\EFI on EFIESP" if split else
                "copy EFI over \\EFI on EFIESP, or onto the microSD card")
    if split:
        report_tree("MainOS tree", payload_root,
                    "copy EFI\\UniXNU\\Payloads to \\EFI\\UniXNU\\Payloads on MainOS")
    print()
    print(f"kernel {header['size']} B, {header['ncmds']} load commands, args {arguments!r}")
    if not split:
        print("note: the whole tree has to fit EFIESP; add --payload-out to keep the kernel on "
              "MainOS instead")
    elif not args.ntfs_driver:
        print("note: no --ntfs-driver, so MainOS is not a volume the firmware can read; the "
              "kernel will not be found there")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
