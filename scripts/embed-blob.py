#!/usr/bin/env python3
"""Turn a binary into a C blob the kernel image can carry.

The storage driver reaches the kernel as an mkext handed to OSKext::loadFromMkext(). This writes that container as two
ordinary C symbols, so a component archive can hold it and the kernel link keeps it without any special build rule:

    const unsigned char lumia_sdhci_mkext[];
    const unsigned long lumia_sdhci_mkext_size;

    python scripts/embed-blob.py --input out/kext/NativeSdhci.mkext --symbol lumia_sdhci_mkext --output blob.cpp
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

COLUMNS = 16


def emit(data: bytes, symbol: str) -> str:
    lines = [
        "// Generated by scripts/embed-blob.py; do not edit.",
        f"// {len(data)} bytes.",
        "",
        f'extern "C" const unsigned char {symbol}[] = {{',
    ]
    for start in range(0, len(data), COLUMNS):
        chunk = data[start:start + COLUMNS]
        rendered = ", ".join(f"0x{byte:02X}" for byte in chunk)
        lines.append(f"    {rendered},")
    lines.append("};")
    lines.append(f'extern "C" const unsigned long {symbol}_size = {len(data)}UL;')
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--input", required=True, type=Path)
    parser.add_argument("--symbol", required=True)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args(argv)

    if not args.input.is_file():
        print(f"error: no input at {args.input}", file=sys.stderr)
        return 2
    if not args.symbol.isidentifier():
        print(f"error: {args.symbol} is not a C identifier", file=sys.stderr)
        return 2

    data = args.input.read_bytes()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(emit(data, args.symbol), encoding="utf-8")
    print(f"{args.output}: {len(data)} bytes as {args.symbol}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
